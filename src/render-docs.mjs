#!/usr/bin/env node
/**
 * Regenerate every human-facing document from data/manifest.json.
 *
 * The README used to be maintained by hand next to the data, so its numbers
 * drifted away from the files: it advertised 142,706 characters for files that
 * held 142,602 rows, and claimed all four emoji statuses were complete while two
 * rows were missing. Docs are now a build artifact - no statistic in any markdown
 * file is typed by a human.
 *
 *   node src/render-docs.mjs
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { ok, log } from './lib/log.mjs';
import { renderReleaseNotes } from './lib/release-notes.mjs';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const manifest = JSON.parse(fs.readFileSync(path.join(ROOT, 'data', 'manifest.json'), 'utf8'));

const n = (v) => v.toLocaleString('en-US');
const kb = (b) => (b > 1048576 ? (b / 1048576).toFixed(2) + ' MB' : (b / 1024).toFixed(1) + ' KB');
const BT = String.fromCharCode(96);
const FENCE = BT + BT + BT;

const UNICODE = manifest.unicodeVersion;
const UCD = manifest.ucdVersion;
const EMOJI = manifest.emojiVersion;
const S = manifest.symbols;

const fileBy = (suffix) => manifest.files.find((f) => f.path.endsWith(suffix));
const tableRow = (suffix, what) => {
  const f = fileBy(suffix);
  if (!f) throw new Error('manifest has no file ending in ' + suffix);
  return '| ' + BT + f.path.split('/')[1] + BT + ' | ' + n(f.lines) + ' | ' + kb(f.bytes) + ' | ' + what + ' |';
};

const blocks = S.blocks;
const nonchar = S.noncharacters;
const fq = S.emojiByStatus['fully-qualified'];
const mq = S.emojiByStatus['minimally-qualified'];
